const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('fs'),os=require('os'),path=require('path');
const DB=require('./db/database'),Backup=require('./db/backup'),Guard=require('./session-guard');
test('tags, recovery, monthly totals, restore permissions and backup persistence',async()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'khata-workflows-')),file=path.join(dir,'test.db');
 const db=new DB(file);await db.init();const admin=db.getUsers()[0];
 const customers=['Customer','Party','Bank','Cash'].map(tag=>db.createCustomer({name:tag,currency:'PKR',tag},admin));
 assert.deepEqual(customers.map(c=>c.tag),['Customer','Party','Bank','Cash']);
 assert.throws(()=>db.createCustomer({name:'Bad',currency:'PKR',tag:'Bad'},admin),/Choose/);
 const aed=db.createCustomer({name:'AED',currency:'AED',opening_balance:10000,opening_balance_type:'Receivable'},admin);
 const data={customer_id:customers[0].id,transaction_date:'2026-09-10',transaction_type:'Credit',amount:12550,description:'Recovery',payment_method:'Bank Transfer',reference_number:'REF',notes:'Keep'};
 const original=db.createTransaction(data,admin),receipt=db.getReceiptByTransactionId(original.transaction.id);
 db.deleteTransaction(original.transaction.id,admin);
 const deleted=db.getDeletedTransactions()[0];
 assert.equal(db.getAllTransactions().length,0);
 assert.throws(()=>db.restoreDeletedTransaction(deleted.id,'restore',{role:'Staff'}),/Administrator/);
 assert.throws(()=>db.restoreDeletedTransaction(deleted.id,' ',admin),/reason/);
 db.setPeriodLock('2026-09-10','Close',admin);
 assert.throws(()=>db.restoreDeletedTransaction(deleted.id,'restore',admin),/closed/);
 db.setPeriodLock('','Open',admin);
 db.createTransaction({...data,amount:1000,transaction_type:'Debit',transaction_date:'2026-08-01'},admin);
 const restored=db.restoreDeletedTransaction(deleted.id,'Mistake',admin);
 assert.equal(restored.transaction_code,original.transaction.transaction_code);
 assert.deepEqual(db.getTransactionHistory(restored.id).map(h=>h.action),['RESTORE','DELETE']);
 assert.equal(db.getTransactionHistory(original.transaction.id).length,0);
 db.deleteTransaction(restored.id,admin);
 const recoveredAgain=db.restoreDeletedTransaction(db.getDeletedTransactions()[0].id,'Second recovery',admin);
 assert.deepEqual(db.getTransactionHistory(recoveredAgain.id).map(h=>h.action),['RESTORE','DELETE','RESTORE','DELETE']);
 restored.id=recoveredAgain.id;
 assert.equal(restored.payment_method,'Bank Transfer');assert.equal(restored.notes,'Keep');
 assert.equal(db.getReceiptByTransactionId(restored.id).receipt_number,receipt.receipt_number);
 assert.throws(()=>db.restoreDeletedTransaction(deleted.id,'again',admin),/already/);
 const summary=db.getMonthlySummary('2026-09');
 const pkr=summary.totals.find(r=>r.currency==='PKR'),ar=summary.totals.find(r=>r.currency==='AED');
 assert.equal(pkr.opening,1000);assert.equal(pkr.credit,12550);assert.equal(pkr.closing,-11550);assert.equal(pkr.count,1);
 assert.equal(ar.opening,10000);assert.equal(ar.closing,10000);assert.equal(ar.credit,0);
 assert.throws(()=>db.getMonthlySummary('2026-13'),/month/);
 assert.equal(db.getMonthlySummary('2024-02').to,'2024-02-29');
 const guard=new Guard(db);await guard.invoke('restoreDeletedTransaction','test',[1,'reason',{role:'Staff'}],args=>assert.equal(args[2].role,'Admin'));
 assert.equal(db.getDeletedTransactions().length,0);
 db.saveToDisk();
 const backup=new Backup(db,path.join(dir,'backups')),snapshot=path.join(dir,'snapshot.db');fs.copyFileSync(file,snapshot);
 db.deleteTransaction(restored.id,admin);await backup.restoreBackup(snapshot,admin);
 assert.equal(db.getDeletedTransactions().length,0);assert.equal(db.getCustomerById(customers[2].id).tag,'Bank');
 // Old backups without tags remain accepted and migrate to the default tag.
 const legacy=new db.SQL.Database(fs.readFileSync(snapshot));legacy.run('ALTER TABLE customers DROP COLUMN tag');fs.writeFileSync(path.join(dir,'legacy.db'),Buffer.from(legacy.export()));legacy.close();
 await backup.restoreBackup(path.join(dir,'legacy.db'),admin);assert.equal(db.getCustomerById(aed.id).tag,'Customer');
 db.db.close();fs.rmSync(dir,{recursive:true,force:true});
});
